-- Лучшая серия за заход в тренажёр: сколько верных подряд ребёнок набрал,
-- прежде чем ошибся.
--
-- Отдельная таблица, а не колонка в drills: миграции прогоняются на каждом
-- старте и обязаны быть идемпотентными, а ALTER TABLE ADD COLUMN в SQLite
-- не умеет IF NOT EXISTS (см. README, раздел про миграции).
--
-- Строка появляется только у заходов с серией от двух: серия из одного —
-- это просто верный ответ, и счётчик в тренажёре его тоже не показывает.
--
-- Рекорда ребёнка здесь нет и не будет: он считается как MAX по заходам.
-- Хранимый отдельно, он разошёлся бы с заходами при первой же правке данных
-- — по той же причине выполнение домашки не хранится полем.
CREATE TABLE IF NOT EXISTS drill_streaks (
  drill_id TEXT PRIMARY KEY,
  best INTEGER NOT NULL
);
