-- Настройки тренажёра, с которыми его задали.
--
-- Отдельной таблицей, а не колонкой в assignment_items: ALTER TABLE ... ADD
-- COLUMN IF NOT EXISTS есть в PostgreSQL, но не в SQLite, а миграции
-- прогоняются на каждом старте — безусловный ALTER упал бы на втором.
--
-- Хранится ровно то, что отличается от настройки тренажёра по умолчанию:
-- «двузначные, без таймера, 20 примеров». Разбирает эти ключи сам тренажёр,
-- он же остаётся единственным местом, где написано, что они значат.
CREATE TABLE IF NOT EXISTS assignment_item_settings (
  item_id TEXT PRIMARY KEY,
  settings TEXT NOT NULL
);
