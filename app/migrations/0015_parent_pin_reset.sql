-- Восстановление кода родителя по ссылке из письма.
--
-- До этой таблицы забытые четыре цифры запирали кабинет навсегда: сменить
-- код можно было только из уже открытого кабинета или предъявив старый
-- (см. setParentPin), а никакого обходного пути не было вовсе. Вместе с
-- кабинетом закрывались отчёты, настройки и подписка — то есть человек,
-- забывший код, не мог и заплатить.
--
-- Таблица своя, а не общая с password_resets, и это не про аккуратность:
-- ссылка на смену пароля не должна уметь менять код родителя, а ссылка на
-- код — пароль. Общая таблица давала бы ровно это, стоило кому-нибудь
-- перепутать адрес страницы.
--
-- Хранится не токен, а его SHA-256 — по той же причине, что и у пароля:
-- ночной дамп базы лежит на диске сервера и не должен открывать чужой
-- кабинет.
CREATE TABLE IF NOT EXISTS parent_pin_resets (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  -- Заполняется в момент смены кода. Ссылка одноразовая: письмо остаётся
  -- в ящике, а ящик может открыть не только владелец.
  used_at TEXT
);

-- По user_id ходят дважды: гасят прошлые заявки при новой и считают, сколько
-- их было за час, чтобы формой не забрасывали ящик.
CREATE INDEX IF NOT EXISTS parent_pin_resets_user ON parent_pin_resets (user_id);
