-- Журнал уничтожения персональных данных.
--
-- Пункт 11.3 политики отсылает порядок уничтожения к «нормативным правовым
-- актам» по 152-ФЗ; такой акт — приказ Роскомнадзора от 28.10.2022 № 179,
-- журнал ведётся по нему. Приказ (п. 5) требует, чтобы
-- выгрузка из журнала называла субъекта, категории уничтоженных данных,
-- систему, причину и дату — поэтому каждая колонка здесь отвечает своему
-- подпункту, и выгрузка получается простым SELECT без раскопок в коде.
--
-- Субъект назван внутренним идентификатором записи — это «иная информация,
-- относящаяся к определённому физическому лицу» из п. 5а: класть в журнал имя
-- или почту значило бы хранить то, что только что уничтожили. Категории и
-- название системы записаны в строку, а не подставляются кодом при чтении:
-- журнал должен читаться сам по себе и через годы, когда код уже другой.
--
-- Ключ — пара (субъект, причина): у одного человека событий может быть два —
-- сначала уничтожение данных по его требованию, спустя три года уничтожение
-- остатков (следа согласий из deleted_accounts). Повтор же одного и того же
-- события (двойной клик, гонка двух запросов) в журнал не дублируется:
-- вставка идёт с ON CONFLICT DO NOTHING по этому ключу.
--
-- Хранится журнал 3 (три) года со дня уничтожения — срок из п. 6 приказа для
-- подтверждающих документов; старше — снимается зачисткой в
-- lib/retention.server.ts, руками его чистить не нужно.
CREATE TABLE IF NOT EXISTS pd_destruction_log (
  subject_id TEXT NOT NULL,      -- п. 5а: id учётной записи (usr_…) или профиля ребёнка (chd_…)
  categories TEXT NOT NULL,      -- п. 5б: перечень категорий уничтоженных данных
  system_name TEXT NOT NULL,     -- п. 5в: наименование информационной системы
  reason TEXT NOT NULL,          -- п. 5г: причина уничтожения
  destroyed_at TEXT NOT NULL,    -- п. 5д: дата уничтожения
  PRIMARY KEY (subject_id, reason)
);
