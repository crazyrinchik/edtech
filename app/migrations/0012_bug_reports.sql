-- Обращения «Сообщить об ошибке».
--
-- Письмо на почту владельца — основной способ узнать о поломке, но
-- письмо теряется: ключ Postbox не задан на стенде, сервис отвечает
-- пятисоткой, адрес уехал в спам. Человеку в этот момент уже сказали
-- «спасибо, получили», и обмануть его нельзя. Поэтому обращение сначала
-- ложится сюда, а письмо уходит вторым шагом; ушло оно или нет,
-- записывается в mailed_at.
--
-- Здесь же и защита от заброса: по этой таблице считается, сколько
-- обращений пришло с одного адреса за час.
CREATE TABLE IF NOT EXISTS bug_reports (
  id TEXT PRIMARY KEY,
  -- Кто написал, если вошёл. Тренажёры и нулевой урок работают без
  -- регистрации, поэтому у половины обращений тут будет NULL.
  user_id TEXT,
  child_id TEXT,
  -- Почта для ответа: своя, если человек её оставил, иначе почта
  -- аккаунта. Пусто — значит, ответить некуда, и это его выбор.
  reply_to TEXT,
  message TEXT NOT NULL,
  -- Адрес страницы, с которой нажали кнопку, и браузер: без них
  -- «ничего не работает» невозможно проверить.
  page TEXT,
  user_agent TEXT,
  -- Не IP, а его SHA-256. Считать обращения за час отпечатка хватает, а
  -- ночной дамп базы не превращается в журнал посещений: адрес — это
  -- персональные данные, и хранить его, когда нужен только счётчик,
  -- незачем.
  ip_hash TEXT,
  created_at TEXT NOT NULL,
  -- Время отправки письма. NULL — письмо не ушло, обращение живёт
  -- только здесь, и увидеть его можно в админке.
  mailed_at TEXT,
  -- Отметка «разобрано», ставится в админке. Список обращений без неё
  -- за месяц превращается в ленту, в которой не видно нового.
  handled_at TEXT
);

-- Два запроса ходят по этой таблице: свежие сверху в админке и счётчик
-- обращений с одного отпечатка за час.
CREATE INDEX IF NOT EXISTS bug_reports_created ON bug_reports (created_at);
CREATE INDEX IF NOT EXISTS bug_reports_ip ON bug_reports (ip_hash, created_at);
