-- Восстановление пароля по ссылке из письма.
--
-- Хранится не сам токен, а его SHA-256. Токен живёт только в письме и в
-- адресной строке того, кто это письмо открыл; в базе от него остаётся
-- отпечаток. Поэтому дамп базы — а он снимается каждую ночь и лежит на
-- диске сервера — не даёт возможности зайти в чужой кабинет. Обратная
-- сторона одна: подсказать человеку его ссылку мы не можем, только
-- выслать новую, и это правильный размен.
--
-- Отдельная таблица, а не колонки в users: у одного человека может быть
-- несколько заявок (нажал дважды, письмо не дошло), у каждой свой срок и
-- своя отметка об использовании, и все они должны гаситься разом при
-- смене пароля.
CREATE TABLE IF NOT EXISTS password_resets (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  -- Заполняется в момент смены пароля. Ссылка одноразовая: письмо могло
  -- остаться в переписке, в истории браузера или у того, кто получил
  -- доступ к почте позже.
  used_at TEXT
);

-- По user_id ходят дважды: гасят прошлые заявки при новой и считают,
-- сколько их было за час, чтобы формой не забрасывали чужой ящик.
CREATE INDEX IF NOT EXISTS password_resets_user ON password_resets (user_id);
