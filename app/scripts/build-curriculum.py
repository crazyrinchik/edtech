def classify(subj, grade, title):
    low = title.lower()
    # «Определение времени по часам» — не деление: слово «определение» несёт в
    # себе «делени» и утаскивало главу в арифметику. Служебные слова убираем
    # до сопоставления.
    for noise in ("определение", "определять", "определяем", "определении"):
        low = low.replace(noise, "")
    # Обучение грамоте — это первое полугодие первого класса, и в каталоге у
    # него свои темы. Отличить его можно только по названию главы: дальше в
    # году те же слоги и звуки идут уже как обычные темы русского языка.
    literacy = any(k in low for k in ("обучение грамоте", "азбук", "букварь", "букварный", "подготовительный период", "списывание"))
    for code, kws in RULES[subj][grade]:
        if code.startswith("r1.gr.") and not literacy:
            continue
        if literacy and subj == "rus" and grade == "1" and not code.startswith("r1.gr."):
            continue
        for kw in kws:
            if kw in low:
                return code
    return None

