/**
 * Подвал экрана итога для того, у кого аккаунт уже есть, но подписки нет.
 *
 * Запирать сами упражнения нельзя — на них ведёт реклама, и первый экран
 * должен отдавать ценность без кассы. Поэтому платит не вход, а память:
 * без подписки заход не пишется в `drills` вовсе (см. saveDrillRow), а
 * значит нет ни рекорда серии, ни дней подряд, ни пёрышек.
 *
 * Отсюда и разговор: не «вам недоступно», а «то, чем ребёнок только что
 * гордился, никуда не легло». Цифру серии называем, только когда она
 * достаточно велика, чтобы её было жалко, — на серии из двух эта фраза
 * звучала бы как насмешка.
 *
 * Цена берётся из lib/billing, а не пишется строкой: она уже разъезжалась
 * с кассой, когда подписку удешевляли.
 */
export function PaywallBridge({ streak }: { streak: number }) {
  const month = planById("month");
  return (
    <aside className="sov-bridge">
      <b>Взрослому</b>
      <p>
        Заход не записан: без подписки Совёнок не хранит ни время, ни рекорд серии, ни пёрышки
        {streak >= 3
          ? ` — а серия сегодня дошла до ${streak}, и завтра сравнить будет не с чем.`
          : " — завтра сравнить будет не с чем."}{" "}
        Подписка включает сохранение, настройку захода и темы по программе класса.
      </p>
      <div className="sov-bridge__acts">
        <StartAction to="/kabinet/podpiska" onClick={() => reachGoal("subscribe-click")}>
          Включить за {priceLabel(month?.amount ?? 399)} в месяц
        </StartAction>
      </div>
    </aside>
  );
}

/**
 * Подвал для того, у кого всё оплачено: заход записан, и единственное, что
 * ему здесь нужно, — знать, куда он лёг. Тихой ссылкой, без кнопки: продавать
 * уже нечего, а экран детский.
 */
export function SavedBridge() {
  return (
    <aside className="sov-bridge">
      <b>Взрослому</b>
      <p>Заход записан: время, серия и пёрышки уже в кабинете.</p>
      <div className="sov-bridge__acts">
        <Link to="/kabinet" className="sov-act-ghost" style={{ textDecoration: "none" }}>
          Прогресс в кабинете
        </Link>
      </div>
    </aside>
  );
}

/**
 * Что показать в подвале экрана итога — один выбор на все пять тренажёров.
 *
 * Раньше в каждом стояло `{!signedIn ? <AdultBridge /> : null}`, и вошедший
 * не получал ничего: ни следующего шага, ни разговора о подписке. Три
 * состояния — три разных предложения, и решаются они здесь, чтобы в пяти
 * экранах не разъехались.
 *
 * `saved === null` — ответа сервера ещё нет: в эту секунду не показываем
 * ничего, иначе на месте «записано» успевала бы мигнуть касса.
 */
export function ResultBridge({
  signedIn,
  saved,
  locked,
  streak,
}: {
  signedIn: boolean;
  saved: boolean | null;
  /** Результату некуда лечь: подписки нет. Отличается от «не вошёл». */
  locked: boolean;
  /** Лучшая серия этого захода — ею и торгуемся. */
  streak: number;
}) {
  if (!signedIn) return <AdultBridge />;
  if (locked) return <PaywallBridge streak={streak} />;
  if (saved) return <SavedBridge />;
  return null;
}

/**
 * Где проходит граница подписки в тренажёрах.
 *
 * Сами упражнения открыты всем и всегда — все пять, без аккаунта и без
 * оплаты. Платного в них два: настройка захода (разрядность, таймер,
 * уровень, набор правил, скорость, размер) и то, что результат где-то
 * остаётся — рекорд серии, динамика в кабинете, пёрышки.
 *
 * Обе подсказки написаны ребёнку, а не взрослому: этот экран открывает он.
 * Ссылки на оплату здесь нет по той же причине, по которой её нет на замке
 * темы, — первоклассник не платит, он показывает экран взрослому.
 */
export function TuneLock() {
  return (
    <p className="sov-setup__lock">
      Настройки — по подписке: сейчас заход идёт как обычно. Покажи этот экран взрослому, подписка
      включается в кабинете.
    </p>
  );
}

