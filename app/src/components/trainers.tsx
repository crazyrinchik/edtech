/**
 * Шапка тренажёра: логотип и переходы в остальные.
 *
 * Полных названий пять, в строку они не встают, поэтому соседи подписаны
 * коротко — «Умножение», «Правописание». Ссылка на занятия стоит последней:
 * из тренажёра выходят реже, чем переходят в соседний.
 *
 * Текущий тренажёр из списка больше не выпадает. Пока он выкидывался,
 * соседи занимали его место, и на каждом экране список был свой: пункт
 * с одним и тем же названием стоял то вторым, то третьим, то нигде.
 * Ребёнок не может опереться на «нажать туда же, где было», если «там же»
 * каждый раз другое. Пять пунктов, постоянный порядок, текущий помечен
 * aria-current — экранный диктор скажет «текущая страница», а глаз
 * увидит подчёркивание. На узком экране строка прокручивается вбок
 * (см. .sov-trainer-nav в brand.css), а не переносится: перенос давал
 * шапку в полтора раза выше самого задания.
 */
export function TrainerTop({
  current,
  lessons = true,
}: {
  current: TrainerId;
  /**
   * Показывать ли выход в «Занятия». По умолчанию да — тренажёр обычно
   * открывают из кабинета ученика, и обратная дорога туда нужна. Экран
   * устного счёта её не показывает (см. routes/schet.tsx).
   */
  lessons?: boolean;
}) {
  return (
    <div className="sov-demo__top">
      <Wordmark compact />
      <nav className="sov-trainer-nav" aria-label="Тренажёры">
        {TRAINERS.map((t) => (
          <Link
            key={t.id}
            to={t.to}
            className="sov-act-ghost"
            style={{ textDecoration: "none" }}
            aria-current={t.id === current ? "page" : undefined}
          >
            {t.short}
          </Link>
        ))}
        {lessons ? (
          <Link to="/uchenik" className="sov-act-ghost" style={{ textDecoration: "none" }}>
            Занятия
          </Link>
        ) : null}
      </nav>
    </div>
  );
}

/**
 * Мостик для взрослого на экране результата.
 *
 * Тренажёры — самая дешёвая дверь в Совёнок, и Директ ведёт рекламу прямо
 * на них: клик стоит единицы рублей, а человек попадает сразу в продукт.
 * Дверь при этом упиралась в стену. Взрослому предлагалось ровно два
 * перехода: кнопка «Сохранить прогресс», то есть регистрация от того, кто
 * ещё не понял, что получит, и серая строка «Родителям: как заниматься дома
 * по программе класса». Одна не объясняла зачем, вторая не выглядела
 * предложением.
 *
 * Теперь это один блок, и в нём сказано то же, что на посадочных: пять
 * тренажёров, темы, кабинет, три минуты на регистрацию. Рядом две двери —
 * аккаунт и рассказ для родителя. Кнопку «Сохранить прогресс» блок заменил
 * собой: два перехода в одну и ту же регистрацию с разными подписями на
 * одном экране — это не выбор, а рябь.
 *
 * Почему не плашка, а подвал карточки с чертой сверху: выше уже стоит
 * цветная подсказка про несохранённый результат, и вторая заливка подряд
 * превратила бы экран ребёнка в рекламный щит. Отсюда же подпись
 * «Взрослому» — ребёнок должен видеть, что этот угол не к нему.
 *
 * Показывается только не вошедшему: у вошедшего всё это уже есть в кабинете.
 */
export function AdultBridge() {
  return (
    <aside className="sov-bridge">
      <b>Взрослому</b>
      {/* Двадцать два слова. Было тридцать — на 375 px это девять строк
          серого текста подряд, и подвал карточки превращался в её половину.
          Подробности ждут за второй ссылкой; здесь сказано ровно то, чего на
          этом экране нет. */}
      <p>
        В Совёнке пять тренажёров, темы по программе класса и кабинет с прогрессом. В аккаунте заход
        не пропадает, а регистрация занимает три минуты.
      </p>
      <div className="sov-bridge__acts">
        {/* Цель Метрики висит на клике: обе двери ведут на публичные адреса,
            и по самому переходу не отличить пришедшего с тренажёра от
            пришедшего с витрины. Отметку надо завести в кабинете Метрики
            как цель-JS-событие с этим же идентификатором, иначе она уходит
            в пустоту (см. reachGoal в lib/metrika.ts). */}
        <Link
          to="/registraciya"
          className="sov-act-ghost"
          style={{ textDecoration: "none" }}
          onClick={() => reachGoal("bridge-signup")}
        >
          Завести аккаунт
        </Link>
        {/* Вторая дверь ведёт на родительскую посадочную, а не на витрину:
            витрина и так открывается по логотипу в шапке этого же экрана, а
            `/roditelyam` иначе не найти. Взрослый, который привёл ребёнка
            размяться в тренажёр, чаще всего родитель, а не педагог. */}
        <Link to="/roditelyam" className="sov-act-ghost" style={{ textDecoration: "none" }}>
          Как заниматься дома
        </Link>
      </div>
    </aside>
  );
}

/**
 * Где проходит граница подписки в тренажёрах.
 *
 * Сами упражнения открыты всем и всегда — все пять, без аккаунта и без
 * оплаты. Платного в них два: настройка захода (разрядность, таймер,
 * уровень, набор правил, скорость, размер) и то, что результат где-то
 * остаётся — рекорд серии, динамика в кабинете, пёрышки.
 *
 * Обе подсказки написаны ребёнку, а не взрослому: этот экран открывает он.
 * Ссылки на оплату здесь нет по той же причине, по которой её нет на замке
 * темы, — первоклассник не платит, он показывает экран взрослому.
 */
export function TuneLock() {
  return (
    <p className="sov-setup__lock">
      Настройки — по подписке: сейчас заход идёт как обычно. Покажи этот экран взрослому, подписка
      включается в кабинете.
    </p>
  );
}

