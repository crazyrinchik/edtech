/**
 * Яндекс.Метрика.
 *
 * Счётчик стоит в <head> одной строкой, синхронно и без обёрток — так его
 * ставит сама Метрика, и так он успевает записать визит до того, как человек
 * закроет вкладку. Всё, что здесь добавлено к официальному сниппету, — три
 * вещи, которых в нём нет и без которых он на этом сайте врал бы.
 *
 * Первая — домен. Счётчик молчит везде, кроме sovenok.space: на превью-стенде
 * платформы и на localhost живёт та же сборка, и без этой проверки в отчёты
 * попадали бы заходы разработчика вперемешку с живыми. Правило то же, что у
 * canonical в lib/seo.ts: прод-адрес прибит гвоздями, а не берётся из запроса.
 *
 * Вторая — список страниц. Счётчик работает только там, где нет данных
 * ребёнка: витрина, тренажёры, юридические документы, вход и регистрация. В
 * кабинетах — взрослого, ребёнка, наставника — он не запускается вовсе. Это не
 * осторожность на всякий случай, а буква пункта 9.3 политики: имя ребёнка на
 * экране кабинета и адрес вида /repetitor/uchenik/<childId> к Яндексу не уходят.
 *
 * Третья — переходы внутри сайта. Совёнок — одностраничное приложение: со
 * страницы тренажёра на оферту роутер уходит без перезагрузки, браузер не
 * дёргает сервер, и Метрика сама по себе такой переход не заметит — весь визит
 * схлопнулся бы в одну первую страницу. Поэтому на каждый разрешённый переход
 * роутера уходит ручной `hit`.
 *
 * Отдельно про Вебвизор: он пишет и то, что человек набирает в форме. Пароли и
 * платёжные реквизиты Метрика маскирует сама, остальное — нет, поэтому все
 * формы Совёнка помечены классами `ym-hide-content ym-disable-keys` (см.
 * `.sov-form` в brand.css). Новая форма получает их вместе с классом `sov-form`.
 */
import { useRouter } from "@tanstack/react-router";
import { useEffect } from "react";

import { PUBLIC_PAGES } from "./seo";

declare global {
  interface Window {
    /** Очередь Метрики: до загрузки tag.js это заглушка, копящая вызовы. */
    ym?: (id: number, action: string, ...args: Array<unknown>) => void;
  }
}

/** Номер счётчика в кабинете Метрики. */
export const METRIKA_ID = 112105785;

/**
 * Хосты, на которых счётчик работает. www здесь на всякий случай: Caddy уводит
 * его редиректом, но если редирект однажды отвалится, статистику терять незачем.
 */
const LIVE_HOSTS = ["sovenok.space", "www.sovenok.space"];

/**
 * Страницы, на которых счётчик работает.
 *
 * Публичные берутся из того же списка, что кормит `sitemap.xml` и `head`
 * страниц: новый тренажёр попадёт под счётчик сам, без правки этого файла, — а
 * забыть внести его сюда невозможно, потому что списка два нет.
 *
 * Дальше — вручную то, чего в публичном списке нет и не будет: вход,
 * регистрация, приглашение и восстановление пароля. В поиске им делать нечего,
 * но именно на них видно, сколько человек с витрины дошло до аккаунта, а данных
 * ребёнка на них нет — то, что вводится и показывается, скрыто от Вебвизора
 * классами на формах и на карточке ученика в `priglashenie.tsx`.
 *
 * Чего здесь нет намеренно: кабинеты (`/roditel`, `/uchenik`, `/repetitor/*`),
 * выбор профиля `/kto`, занятие `/urok/*`, оплата и админка.
 */
const COUNTED_PATHS: Array<string> = [
  ...Object.keys(PUBLIC_PAGES),
  "/vhod",
  "/registraciya",
  "/priglashenie",
  "/vosstanovlenie",
  "/novyy-parol",
];

/**
 * Один и тот же разбор адреса и на сервере, и внутри инлайнового сниппета:
 * хвостовой слэш отрезается (иначе «/oferta/» не совпал бы со списком),
 * параметры запроса игнорируются — `/shulte?size=4` это та же страница.
 */
export function isCountedPath(pathname: string): boolean {
  const path = pathname.length > 1 ? pathname.replace(/\/+$/, "") : pathname;
  return COUNTED_PATHS.includes(path === "" ? "/" : path);
}

/**
 * Сниппет из кабинета Метрики, внутри проверок домена и страницы.
 *
 * От присланного из кабинета он отличается одним снятым параметром:
 * ecommerce:"dataLayer". Электронной торговли на сайте нет — подписку принимает
 * ТБанк на своей странице, и событий о товарах и корзине Совёнок не шлёт. Опция
 * заводила пустой window.dataLayer и обещала отчёту данные, которых не будет;
 * в кабинете счётчика она выключена 01.09.2026. Возвращать её имеет смысл
 * только вместе с кодом, который начнёт эти события отправлять.
 *
 * Проверки снаружи, а не первой строкой внутри — потому что `ym(...)`
 * вызывается уже после IIFE: выйди мы из неё раньше времени, заглушки
 * `window.ym` не появилось бы и следующая же строка упала бы с ReferenceError
 * на глазах у посетителя.
 *
 * Если человек зашёл сразу в кабинет, счётчик не заведётся и на переходах
 * оттуда на витрину — и это правильно: считаем посетителей с улицы, а не
 * хождение хозяина аккаунта по своим страницам.
 */
const COUNTER = `
(function () {
  var host = window.location.hostname;
  if (${JSON.stringify(LIVE_HOSTS)}.indexOf(host) === -1) { return; }

  var path = location.pathname.length > 1 ? location.pathname.replace(/\\/+$/, "") : location.pathname;
  if (${JSON.stringify(COUNTED_PATHS)}.indexOf(path === "" ? "/" : path) === -1) { return; }

  (function(m,e,t,r,i,k,a){
      m[i]=m[i]||function(){(m[i].a=m[i].a||[]).push(arguments)};
      m[i].l=1*new Date();
      for (var j = 0; j < document.scripts.length; j++) {if (document.scripts[j].src === r) { return; }}
      k=e.createElement(t),a=e.getElementsByTagName(t)[0],k.async=1,k.src=r,a.parentNode.insertBefore(k,a)
  })(window, document,'script','https://mc.yandex.ru/metrika/tag.js?id=${METRIKA_ID}', 'ym');

  ym(${METRIKA_ID}, 'init', {ssr:true, webvisor:true, clickmap:true, referrer: document.referrer, url: location.href, accurateTrackBounce:true, trackLinks:true});
})();
`.trim();

/** Скрипты счётчика для `head()` корневого роута. */
export function metrikaHeadScripts() {
  return [{ children: COUNTER }];
}

/**
 * Досылает Метрике переходы внутри приложения.
 *
 * Первую страницу визита считает сам `init`, поэтому адрес сравнивается с
 * предыдущим: без этого начало визита ушло бы дважды и все отказы поехали бы.
 *
 * Уход в кабинет хитом не считается: адрес страницы, на которую человек ушёл,
 * проверяется по тому же списку. Иначе в отчёт попал бы адрес с идентификатором
 * профиля ребёнка — ровно то, чего мы избегаем.
 *
 * По той же причине несчитаемая страница не запоминается как предыдущая. Иначе
 * она вернулась бы к Яндексу с чёрного хода — полем `referer` следующего хита:
 * человек уходит с витрины в кабинет ученика, возвращается на витрину, и в
 * отчёте «источник перехода» оказывается /repetitor/uchenik/<childId>.
 *
 * Сам хит уходит через setTimeout(0): `onResolved` срабатывает, когда роутер
 * разобрался с маршрутом, а <title> дорисовывает следом React — без отсрочки в
 * отчёт рискует попасть имя страницы, с которой человек ушёл, а не той, на
 * которую пришёл. Отсрочка именно таймером, а не requestAnimationFrame: кадры в
 * фоновой вкладке браузер не рисует, и хит бы там просто не ушёл.
 */
export function useMetrikaPageviews() {
  const router = useRouter();

  useEffect(() => {
    let previous = isCountedPath(window.location.pathname) ? window.location.href : null;

    return router.subscribe("onResolved", () => {
      const url = window.location.href;
      if (url === previous) return;
      if (!isCountedPath(window.location.pathname)) return;

      const referer = previous;
      previous = url;

      setTimeout(() => {
        window.ym?.(METRIKA_ID, "hit", url, {
          ...(referer ? { referer } : {}),
          title: document.title,
        });
      }, 0);
    });
  }, [router]);
}
