const cap = (s: string) => s[0].toUpperCase() + s.slice(1);

/** Карточка «вставь букву» из банка [слово с пропуском, буква, подсказка]. */
const gapTask =
  (bank: readonly [string, string, string][], hint: (rule: string) => string): Family =>
  (r) => {
    const [word, letter, rule] = r.pick(bank);
    return input(`Вставь пропущенную букву: ${word}`, letter, hint(rule));
  };

/** Слово с пропуском на месте буквы с номером i. */
const gapAt = (word: string, i: number) => `${word.slice(0, i)}_${word.slice(i + 1)}`;

