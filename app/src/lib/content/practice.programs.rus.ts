const nsh21Morphemics: Family[] = [
  (r) => {
    const [word, way, base, how] = r.pick(WAYS);
    return pickOne(
      r,
      `Каким способом образовано слово «${word}»?`,
      way,
      WAY_LIST,
      `«${word}» образовано от слова «${base}»: ${how}. Способ — ${way}.`,
    );
  },
  (r) => {
    const [word, , base, how] = r.pick(WAYS);
    return input(
      `От какого слова образовано слово «${word}»? Напиши это слово.`,
      base,
      `Убираем то, чем слово образовано (${how}), и остаётся «${base}».`,
    );
  },
  (r) => {
    const [base, prefix, result] = r.pick(PREFIX_FORM);
    return input(
      `Образуй слово с приставкой ${prefix}- от слова «${base}».`,
      result,
      `Приставка ставится перед корнем: ${prefix}- + ${base} = ${result}. Это приставочный способ.`,
    );
  },
  (r) => {
    const [base, suffix, result] = r.pick(SUFFIX_FORM);
    return input(
      `Образуй слово с суффиксом -${suffix} от слова «${base}».`,
      result,
      `Суффикс ставится после корня: ${base} + -${suffix} = ${result}. Это суффиксальный способ.`,
    );
  },
  // Найти приставку или суффикс в готовом слове — обратная задача к образованию.
  (r) => {
    if (r.int(0, 1) === 0) {
      const [base, prefix, result] = r.pick(PREFIX_FORM);
      return input(
        `Выдели приставку в слове «${result}». Напиши только приставку.`,
        prefix,
        `Слово образовано от «${base}», часть перед корнем — приставка ${prefix}-.`,
      );
    }
    const [base, suffix, result] = r.pick(SUFFIX_FORM);
    return input(
      `Выдели суффикс в слове «${result}». Напиши только суффикс.`,
      suffix,
      `Слово образовано от «${base}», часть после корня — суффикс -${suffix}.`,
    );
  },
  (r) => {
    if (r.int(0, 2) === 0) {
      const triple = r
        .shuffle(["ик", "ищ", "ёнок"])
        .map((s) => r.pick(SUFFIX_FORM.filter((x) => x[1] === s)));
      return match(
        `Соедини слово и значение его суффикса: ${triple.map((t) => t[2]).join(", ")}.`,
        triple.map((t) => [t[2], t[3]] as [string, string]),
        "Суффикс -ик — маленький, -ищ- — очень большой, -ёнок — детёныш.",
      );
    }
    const [base, suffix, result, meaning] = r.pick(SUFFIX_FORM);
    return pickOne(
      r,
      `Что обозначает суффикс -${suffix} в слове «${result}»?`,
      meaning,
      ["маленький", "очень большой", "детёныш"],
      `${cap(result)} — это ${meaning} ${base === "лис" ? "лисы" : base}. Суффикс добавляет к корню своё значение.`,
    );
  },
  (r) => {
    const [word, scheme, parse] = r.pick(SCHEMES);
    return pickOne(
      r,
      `По какой схеме построено слово «${word}»?`,
      scheme,
      r.shuffle(SCHEME_LIST.filter((s) => s !== scheme)),
      `Разбираем: ${parse}. Схема — ${scheme}.`,
    );
  },
  (r) => {
    const [word, scheme, parse] = r.pick(SCHEMES);
    const others = r.shuffle(SCHEMES.filter((s) => s[1] !== scheme)).slice(0, 2);
    const listed = r.shuffle([word, ...others.map((o) => o[0])]);
    return pickOne(
      r,
      `Какое слово построено по схеме «${scheme}»: ${listed.join(", ")}?`,
      word,
      others.map((o) => o[0]),
      `${cap(word)}: ${parse}. ${others.map((o) => `${cap(o[0])}: ${o[2]}`).join(". ")}.`,
    );
  },
  (r) => {
    const [word, form, cognate] = r.pick(ROOT_VS_FORM);
    const isForm = r.int(0, 1) === 0;
    const pair = isForm ? `${word} — ${form}` : `${word} — ${cognate}`;
    return pickOne(
      r,
      `«${pair}»: это формы одного слова или однокоренные слова?`,
      isForm ? "формы одного слова" : "однокоренные слова",
      ["формы одного слова", "однокоренные слова"],
      isForm
        ? `У слов «${word}» и «${form}» меняется только окончание, значение то же — это формы одного слова.`
        : `У слов «${word}» и «${cognate}» общий корень, но разное значение и разные части слова — это однокоренные слова.`,
    );
  },
];

