/** Вопрос из банка [вопрос, ответ, лишние варианты, разбор]. */
const qaFamily =
  (bank: readonly [string, string, string[], string][], tail = ""): Family =>
  (r) => {
    const [question, answer, distractors, why] = r.pick(bank);
    return pickOne(r, `${question}${tail}`, answer, distractors, why);
  };

