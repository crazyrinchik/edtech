const count = (n: number, t: [string, string, string]) => `${n} ${plural(n, t[0], t[1], t[2])}`;
const times = (n: number) => `${n} ${plural(n, "раз", "раза", "раз")}`;
const merki = (n: number) => `${n} ${plural(n, "мерка", "мерки", "мерок")}`;
const cmpSign = (a: number, b: number) => (a > b ? ">" : a < b ? "<" : "=");

/** Два разных имени: в задачах про «у кого больше» одно имя дважды — нелепость. */
function twoKids(r: Rng): [[string, string], [string, string]] {
  const [a, b] = r.shuffle(KIDS);
  return [a, b];
}

