/** Числа, отличные от уже взятых: множества из повторов не собирают. */
function distinctInts(r: Rng, n: number, min: number, max: number): number[] {
  const out: number[] = [];
  while (out.length < n) {
    const x = r.int(min, max);
    if (!out.includes(x)) out.push(x);
  }
  return out;
}

