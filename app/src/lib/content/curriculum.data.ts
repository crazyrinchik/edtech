export type SubjectId = "math" | "rus";

export type CatalogTopic = {
  code: string;
  subject: SubjectId;
  grade: number;
  title: string;
  /** Часы по федеральной рабочей программе — ориентир, сколько тема идёт в школе. */
  hours: number | null;
};

/** Глава учебника: своя формулировка программы и тема каталога за ней. */
export type ProgramStep = { title: string; code: string | null };

export type ProgramInfo = {
  id: string;
  name: string;
  short: string;
  /** Распространённость — репетитору важнее авторов: по ней он узнаёт учебник. */
  share: string | null;
  authors: Partial<Record<SubjectId, string>>;
  note: string;
  confidence: "verified" | "high" | "medium" | "low";
  isDefault: boolean;
  /** Петерсон в каталоге только по математике — русский у школы другой. */
  subjects: SubjectId[];
  warning: string | null;
  steps: Record<SubjectId, Record<string, ProgramStep[]>>;
};

/** Чем программа отличается от базового темпа: опережение и свои темы. */
export type ProgramDelta = {
  program: string;
  subject: SubjectId;
  grade: number;
  type: "ahead" | "extra" | "baseline" | "behind" | "terminology" | string;
  what: string;
  impact: string;
};

