// Стартовый контент «Совёнка»: 2 предмета x 2 класса x 5 тем.
// Задания описаны генераторами, чтобы каждую тему можно было наполнить
// быстро, а администратор потом правил их через админ-панель.

export type TaskPayload = { options?: string[]; left?: string[]; right?: string[] };

export type SeedTask = {
  kind: "choice" | "input" | "match";
  prompt: string;
  payload: TaskPayload;
  answer: string;
  explanation: string;
  isCheck: boolean;
};

export type SeedTopic = {
  id: string;
  subjectId: "math" | "rus";
  grade: number;
  name: string;
  summary: string;
  isFree: boolean;
  tasks: SeedTask[];
};

const choice = (
  prompt: string,
  options: string[],
  answer: string,
  explanation: string,
  isCheck = false,
): SeedTask => ({ kind: "choice", prompt, payload: { options }, answer, explanation, isCheck });

const input = (
  prompt: string,
  answer: string,
  explanation: string,
  isCheck = false,
): SeedTask => ({ kind: "input", prompt, payload: {}, answer, explanation, isCheck });

const match = (
  prompt: string,
  pairs: [string, string][],
  explanation: string,
  isCheck = false,
): SeedTask => ({
  kind: "match",
  prompt,
  payload: { left: pairs.map((p) => p[0]), right: pairs.map((p) => p[1]) },
  answer: pairs.map((p) => p[1]).join("|"),
  explanation,
  isCheck,
});

// Небольшой детерминированный «случайный» ряд, чтобы наборы не повторялись.
function series(seed: number, count: number, max: number): number[] {
  const out: number[] = [];
  let x = seed;
  for (let i = 0; i < count; i += 1) {
    x = (x * 1103515245 + 12345) % 2147483648;
    out.push((x % max) + 1);
  }
  return out;
}

function addition(seed: number, limit: number, count: number, isCheck: boolean): SeedTask[] {
  const a = series(seed, count, limit - 1);
  const b = series(seed + 7, count, limit - 1);
  return a.map((x, i) => {
    const y = Math.min(b[i], limit - x > 0 ? limit - x : 1);
    return input(
      `Сколько будет ${x} + ${y}?`,
      String(x + y),
      `Прибавляем по частям: ${x} и ещё ${y}. Получается ${x + y}. Можно посчитать на пальцах или отложить ${x} палочек и добавить ещё ${y}.`,
      isCheck,
    );
  });
}

function subtraction(seed: number, limit: number, count: number, isCheck: boolean): SeedTask[] {
  const a = series(seed, count, limit);
  const b = series(seed + 13, count, limit);
  return a.map((x, i) => {
    const big = Math.max(x, b[i]);
    const small = Math.min(x, b[i]);
    return input(
      `Сколько будет ${big} − ${small}?`,
      String(big - small),
      `Из ${big} убираем ${small}. Осталось ${big - small}. Проверить легко: ${big - small} + ${small} снова даёт ${big}.`,
      isCheck,
    );
  });
}

function compare(seed: number, limit: number, count: number, isCheck: boolean): SeedTask[] {
  const a = series(seed, count, limit);
  const b = series(seed + 31, count, limit);
  return a.map((x, i) => {
    const y = b[i] === x ? b[i] + 1 : b[i];
    const sign = x > y ? ">" : "<";
    return choice(
      `Какой знак поставить: ${x} … ${y}?`,
      [">", "<", "="],
      sign,
      `${x} ${sign} ${y}. Клювик знака всегда смотрит на меньшее число, а раскрытая сторона — на большее.`,
      isCheck,
    );
  });
}

