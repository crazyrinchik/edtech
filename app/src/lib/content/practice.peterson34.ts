const cmpSign = (a: number, b: number) => (a > b ? ">" : a < b ? "<" : "=");

/** Круглые двузначные множители и делители: 20, 30, … 90. */
const ROUND_TENS = [20, 30, 40, 50, 60, 70, 80, 90];

/** Знаменатели, с которыми дроби читаются просто: «пятых», «восьмых». */
