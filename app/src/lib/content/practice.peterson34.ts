/*
 * «Учусь учиться» (Л. Г. Петерсон), математика, 3 и 4 класс.
 *
 * Программа идёт заметно впереди базового темпа: в 3 классе многозначные
 * числа до миллиона, столбик и уголок с многозначными, формулы пути,
 * стоимости, работы, составные уравнения и буквенные выражения. В 4 классе
 * обыкновенные дроби и смешанные числа, проценты, неравенства и оценка
 * результата, скорость сближения и удаления, углы и транспортир, координаты
 * на плоскости. Общий набор этого уровня не даёт, поэтому у всех четырнадцати
 * тем свои генераторы. Условия придуманы здесь, из программы взяты только
 * числа, действия и термины.
 *
 * Ответы с дробями: обыкновенная дробь — «2/5», смешанное число — «2 1/3».
 * Знаменатель в ответе не меняем: сокращение дробей в 4 классе ещё не
 * изучают, а ребёнок сверяется строкой.
 */

