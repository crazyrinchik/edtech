const parts = (n: number) => `${n} ${plural(n, "равную часть", "равные части", "равных частей")}`;

/** Округление «по правилу»: пятёрка и больше — вверх, как учат в школе. */
const roundTo = (n: number, unit: number) => Math.round(n / unit) * unit;

