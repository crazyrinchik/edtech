/**
 * Акция «SOVENOK50»: половина цены на месяц или год для тех, кто уже был
 * зарегистрирован к её запуску.
 *
 * Общий файл для клиента и сервера, как и billing.ts: цена со скидкой в
 * форме и цена в счёте должны считаться одной функцией. Секретов нет —
 * сам код и так напечатан на баннере.
 */

export const PROMO_CODE = "SOVENOK50";
export const PROMO_PERCENT = 50;

/**
 * Кто считается «действующим» пользователем: зарегистрированный до этого
 * момента. Тем, кто заведёт учётную запись позже, баннер не показывается,
 * а код не срабатывает. Дата — момент запуска акции в UTC.
 */
export const PROMO_SIGNUP_BEFORE = "2026-09-10T00:00:00.000Z";

/**
 * Скидка округляется в пользу покупателя: 399 → 199, 3 999 → 1 999.
 * Иначе «скидка 50%» на нечётную цену была бы скидкой 49,9%.
 */
export function discountedAmount(amount: number): number {
  return Math.floor(amount * (1 - PROMO_PERCENT / 100));
}

/** Как код печатается и сравнивается: без пробелов, в верхнем регистре. */
export function normalizePromo(code: string): string {
  return code.replace(/\s+/g, "").toUpperCase();
}
