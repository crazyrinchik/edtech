/**
 * Тарифы подписки. Один файл на клиент и на сервер — цена в форме оплаты и
 * цена в счёте берутся из одного места.
 *
 * Секретов здесь нет и быть не может: файл попадает в браузерный бандл.
 * Ключи терминала T-Bank живут в tbank.server.ts.
 *
 * Тариф один на обе платящие роли. Родитель открывает темы своим детям,
 * репетитор — всем своим ученикам; цену это не меняет, потому что платит
 * всегда один взрослый, который привёл ребёнка (см. блок «Сколько это
 * стоит» на витрине).
 */

export type PlanId = "month" | "year";

export type Plan = {
  id: PlanId;
  /** Как называется в форме оплаты. */
  title: string;
  /** Рублей за период, целыми. В копейки их переводит tbank.server.ts. */
  amount: number;
  months: number;
  /** Строка для чека и назначения платежа. Уходит в кассу как есть. */
  receipt: string;
  note: string | null;
};

export const PLANS: Plan[] = [
  {
    id: "month",
    title: "Месяц",
    amount: 1499,
    months: 1,
    receipt: "Подписка «Совёнок» на 1 месяц",
    note: null,
  },
  {
    id: "year",
    title: "Год",
    amount: 14999,
    months: 12,
    receipt: "Подписка «Совёнок» на 12 месяцев",
    note: "Два месяца в подарок",
  },
];

export function planById(id: string): Plan | undefined {
  return PLANS.find((p) => p.id === id);
}

/**
 * Сколько профилей можно завести без подписки.
 *
 * Один. Раньше бесплатный режим не ограничивал их числом вовсе, и витрина
 * честно обещала «сколько угодно учеников»: репетитор мог вести хоть
 * двадцать семей, а подписка добавляла только темы. Теперь она добавляет
 * и учеников, и это надо было сказать во всех местах разом — иначе
 * обещание на витрине разошлось бы с отказом в кабинете.
 *
 * Ограничение считается по уже заведённым профилям и работает только в
 * момент создания нового. Тот, у кого их уже больше, ничего не теряет,
 * когда подписка кончается: отобрать заведённого ученика значит отобрать
 * у ребёнка его занятия, а это не то, чем торгуют.
 *
 * Приглашённых это не касается вовсе: профиль ребёнка создаёт репетитор,
 * а родитель по приглашению получает доступ к готовому. Семья с двумя
 * детьми у платящего репетитора ограничения не увидит никогда.
 */
export const FREE_CHILD_LIMIT = 1;

/**
 * «1 499 ₽» — неразрывные пробелы и в разряде, и перед знаком рубля: цена
 * не должна разрываться переносом строки ни в одном месте.
 *
 * Пробел записан escape-последовательностью, а не самим символом: в
 * исходнике неразрывный пробел неотличим от обычного и переживает не
 * всякую правку.
 */
const NBSP = "\u00A0";

export function priceLabel(amount: number): string {
  return `${amount.toLocaleString("ru-RU").replace(/\s/g, NBSP)}${NBSP}₽`;
}
