/**
 * Лавка совёнка: что можно купить за пёрышки.
 *
 * Рост совёнка сюда не входит — он идёт от уровня и достаётся сам. Здесь
 * только аксессуары, и каждый из них ребёнок выбирает и покупает сам.
 * Уровень задаёт, когда вещь появляется на витрине, а цена — сколько за
 * ней работать: без порога по уровню всё скупалось бы в первый день, без
 * цены покупка не была бы наградой.
 */
export type ShopItem = {
  id: Exclude<OwlItem, "none">;
  title: string;
  note: string;
  cost: number;
  minLevel: number;
};

/** Пёрышки за работу. Домашка даёт меньше темы, но и делается чаще. */
export const COINS_PER_HOMEWORK_ITEM = 5;
export const COINS_PER_TOPIC = 10;

/**
 * Тренажёр — самая частая работа, поэтому и самая дешёвая.
 *
 * Раньше он не приносил пёрышек вовсе: начисления знали только домашку и
 * темы. Пока тренажёры были приманкой на витрине, это сходило с рук, но
 * теперь ребёнок заходит в них каждый день, и заход, который ничего не
 * оставляет, читается как «это не считается».
 */
export const COINS_PER_DRILL = 3;

/**
 * Сколько заходов в день оплачивается.
 *
 * Без предела пёрышки фармятся за минуту: таблица Шульте три на три
 * закрывается за двадцать секунд, и десять заходов подряд дали бы больше,
 * чем пройденная тема. Три — это примерно два разных тренажёра за вечер,
 * то есть то, ради чего всё и затевалось.
 *
 * Заходы сверх предела не пропадают для отчёта родителя — они просто не
 * добавляют пёрышек.
 */
export const PAID_DRILLS_PER_DAY = 3;

/**
 * Какую долю верных считать заходом, а не пробой пера.
 *
 * Тот же порог, что у проверочной работы: ниже семидесяти процентов тема
 * не засчитывается, и тренажёр не должен быть щедрее. Для таблицы Шульте
 * это доля попаданий среди всех нажатий.
 */
export const DRILL_PAID_SHARE = 0.7;

/**
 * Какие заходы оплачиваются пёрышками.
 *
 * Принимает строки в том порядке, в каком их отдаёт база — от новых к
 * старым, — и возвращает те, за которые положена награда.
 *
 * Считается это здесь, а не запросом: «первые три захода за сутки» —
 * оконная функция, а SQL уезжает и в D1, и в шлюз к PostgreSQL, и держать
 * один смысл в двух диалектах дороже, чем отобрать строки в памяти.
 *
 * Порядок внутри дня важен: предел достаётся первым заходам, а не
 * последним. Иначе вчерашняя награда исчезала бы задним числом, стоило
 * ребёнку позаниматься ещё раз, — а начисления уже выданы и списывать их
 * никто не станет.
 *
 * День берётся из начала ISO-строки, то есть по UTC: занятие после трёх
 * ночи по Москве попадёт в следующие сутки, и это ровно то, чего мы ждём
 * от предела «в день».
 */
export function pickPaidDrills<T extends { correct: number; total: number; created_at: string }>(
  rows: readonly T[],
): T[] {
  const perDay = new Map<string, number>();
  const paid: T[] = [];
  for (const row of rows.slice().reverse()) {
    if (!row.total || row.correct / row.total < DRILL_PAID_SHARE) continue;
    const day = row.created_at.slice(0, 10);
    const used = perDay.get(day) ?? 0;
    if (used >= PAID_DRILLS_PER_DAY) continue;
    perDay.set(day, used + 1);
    paid.push(row);
  }
  return paid;
}

