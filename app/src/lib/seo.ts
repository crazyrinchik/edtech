export type PublicPath = keyof typeof PUBLIC_PAGES;

/** Разметка витрины: кто издаёт сайт. Отдельным `@graph`, чтобы страницы
 *  тренажёров могли сослаться на ту же организацию по `@id`. */
function siteJsonLd() {
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "EducationalOrganization",
        "@id": ORG_ID,
        name: "Совёнок",
        url: SITE_ORIGIN,
        logo: LOGO_URL,
        description: PUBLIC_PAGES["/"].description,
        inLanguage: "ru-RU",
      },
      {
        "@type": "WebSite",
        "@id": `${SITE_ORIGIN}/#site`,
        url: SITE_ORIGIN,
        name: "Совёнок",
        inLanguage: "ru-RU",
        publisher: { "@id": ORG_ID },
      },
    ],
  };
}

/**
 * Разметка тренажёра. `isAccessibleForFree` здесь не украшение: она —
 * причина, по которой поисковик показывает такую страницу человеку,
 * который ищет «таблица умножения тренажёр», а не платный курс.
 */
function trainerJsonLd(path: PublicPath) {
  const page = PUBLIC_PAGES[path];
  return {
    "@context": "https://schema.org",
    "@type": "LearningResource",
    name: page.title.replace(", Совёнок", ""),
    description: page.description,
    url: `${SITE_ORIGIN}${path}`,
    inLanguage: "ru-RU",
    isAccessibleForFree: true,
    learningResourceType: "Интерактивный тренажёр",
    educationalLevel: "Начальная школа, 1–4 класс",
    typicalAgeRange: "7-11",
    provider: { "@id": ORG_ID },
  };
}

/**
 * `head` публичной страницы: заголовок, описание, canonical и карточка для
 * мессенджера.
 *
 * canonical всегда без параметров запроса. Настройки тренажёра ездят в
 * адресе (`?size=4`, `?ops=mul`), и без этой строки каждая комбинация была
 * бы для робота отдельной страницей с тем же текстом.
 */
export function pageHead(path: PublicPath) {
  const page = PUBLIC_PAGES[path];
  const url = `${SITE_ORIGIN}${path}`;
  // Документам разметки не достаётся вовсе, и это не пропуск. Ветка на два
  // случая («витрина или всё остальное») выдавала оферте и политике
  // LearningResource: «интерактивный тренажёр», «1–4 класс», «7-11 лет».
  // Разметка, которая врёт про содержимое, хуже отсутствующей — поисковик
  // сверяет её со страницей. А сказать про договор структурно нечего:
  // заголовок, описание и canonical у него уже есть.
  const jsonLd =
    page.kind === "site" ? siteJsonLd() : page.kind === "trainer" ? trainerJsonLd(path) : null;
  return {
    meta: [
      { title: page.title },
      { name: "description", content: page.description },
      // max-image-preview:large — от него зависит, покажет ли Google рядом
      // со ссылкой акварель или ничего. max-snippet:-1 снимает ограничение
      // на длину описания в выдаче.
      { name: "robots", content: "index, follow, max-image-preview:large, max-snippet:-1" },
      { property: "og:title", content: page.title },
      { property: "og:description", content: page.description },
      { property: "og:url", content: url },
      ...(jsonLd ? [{ "script:ld+json": jsonLd }] : []),
    ],
    links: [{ rel: "canonical", href: url }],
  };
}

/**
 * `head` страницы, которой в поиске делать нечего: кабинеты, вход,
 * регистрация, оплата, приглашение, занятие конкретного ученика.
 *
 * `noindex, follow`, а не `noindex, nofollow`: робот не показывает страницу
 * в выдаче, но по ссылкам с неё дойти до витрины и документов может.
 * Запрещать эти адреса в robots.txt при этом нельзя — запрет на обход
 * означает, что робот не прочитает и сам noindex, и адрес всё равно
 * всплывёт в выдаче голой ссылкой.
 */
export function closedHead(title: string) {
  return {
    meta: [{ title }, { name: "robots", content: "noindex, follow" }],
  };
}
