/*
 * Как это устроено у репетитора: два разворота и пара карточек.
 *
 * Раньше все четыре шага шли одной раскладкой «текст слева, картинка
 * справа» с зеркалированием — две с лишним тысячи пикселей одинакового
 * зигзага, где третий и четвёртый экран отличались от первых двух только
 * словами. Глаз на третьем повторе перестаёт читать и начинает листать.
 *
 * Первые два шага — про то, что репетитор делает руками (заводит ученика,
 * задаёт домашку), и разворот с крупным кадром им к месту. Третий и
 * четвёртый — про то, что происходит дальше само (видно зоны риска,
 * подключается родитель), и они стоят парой: рядом их и читают, сравнивая.
 *
 * Счётчик «Шаг N из 4» снят. Он появился, чтобы читатель видел конец
 * списка, но лечил симптом: конец не был виден потому, что четыре
 * одинаковых блока сливались в один. Теперь их видно три, и считать
 * нечего.
 */
